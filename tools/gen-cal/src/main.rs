//! 一次性/可复现的历法数据生成器。
//!
//! 数据来源：mingli-astro 1.2.0（Meeus 截断模型，太阳黄经 ~0.01°，朔 ~数分钟）。
//! 输出状态固定为 PENDING，待权威历书交叉校核后升 VERIFIED/FROZEN。

use std::path::{Path, PathBuf};

use chrono::{DateTime, Datelike, FixedOffset, TimeZone, Utc};
use serde_json::json;

const TERMS: [(&str, f64); 24] = [
    ("小寒", 285.0),
    ("大寒", 300.0),
    ("立春", 315.0),
    ("雨水", 330.0),
    ("惊蛰", 345.0),
    ("春分", 0.0),
    ("清明", 15.0),
    ("谷雨", 30.0),
    ("立夏", 45.0),
    ("小满", 60.0),
    ("芒种", 75.0),
    ("夏至", 90.0),
    ("小暑", 105.0),
    ("大暑", 120.0),
    ("立秋", 135.0),
    ("处暑", 150.0),
    ("白露", 165.0),
    ("秋分", 180.0),
    ("寒露", 195.0),
    ("霜降", 210.0),
    ("立冬", 225.0),
    ("小雪", 240.0),
    ("大雪", 255.0),
    ("冬至", 270.0),
];

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let mode = args.get(1).map(String::as_str).unwrap_or("all");
    let root = args
        .get(2)
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("resources/cal"));

    match mode {
        "cal" | "all" => {
            gen_lunar(&root);
            gen_jieqi(&root);
        }
        "baseline" => gen_baselines(&root),
        other => {
            eprintln!("未知模式: {other}（cal|baseline|all）");
            std::process::exit(2);
        }
    }
    if mode == "all" {
        gen_baselines(&root);
    }
}

fn gen_lunar(root: &Path) {
    let start = cal::jdn_from_ymd(1900, 1, 31);
    let end = cal::jdn_from_ymd(2101, 2, 28);

    let mut months: Vec<serde_json::Value> = Vec::new();
    let mut current: Option<(i64, i32, u32, bool)> = None;

    for jdn in start..=end {
        let (y, m, d) = cal::ymd_from_jdn(jdn);
        let lunar = mingli_astro::solar_to_lunar(y, m, d, 8.0);
        if lunar.day == 1 {
            if let Some((start_jdn, ly, lm, leap)) = current.take() {
                let days = (jdn - start_jdn) as u32;
                if start_jdn <= cal::jdn_from_ymd(2100, 12, 31) {
                    let (sy, sm, sd) = cal::ymd_from_jdn(start_jdn);
                    months.push(json!({
                        "start": format!("{sy:04}-{sm:02}-{sd:02}"),
                        "year": ly,
                        "month": lm,
                        "leap": leap,
                        "days": days,
                    }));
                }
            }
            current = Some((jdn, lunar.year, lunar.month, lunar.leap));
        }
    }
    if let Some((start_jdn, ly, lm, leap)) = current {
        let days = (cal::jdn_from_ymd(2101, 3, 1) - start_jdn) as u32;
        if start_jdn <= cal::jdn_from_ymd(2100, 12, 31) {
            let (sy, sm, sd) = cal::ymd_from_jdn(start_jdn);
            months.push(json!({
                "start": format!("{sy:04}-{sm:02}-{sd:02}"),
                "year": ly,
                "month": lm,
                "leap": leap,
                "days": days,
            }));
        }
    }

    let doc = json!({
        "version": "CAL-DATA-v0.1",
        "status": "PENDING",
        "reference_tz": "+08:00",
        "source": "mingli-astro 1.2.0 (Meeus truncated); generated by tools/gen-cal",
        "generated_at": "2026-11-03",
        "months": months,
    });
    write_json(&root.join("lunar_months.json"), &doc);
    println!("lunar months: {}", doc["months"].as_array().unwrap().len());
}

fn gen_jieqi(root: &Path) {
    let tz = FixedOffset::east_opt(8 * 3600).unwrap();
    let mut events: Vec<(DateTime<Utc>, serde_json::Value)> = Vec::new();

    for year in 1899..=2101 {
        for (term, (name, target)) in TERMS.iter().enumerate() {
            let jd = mingli_astro::solar_term_jd(year, *target);
            let utc = jd_to_utc(jd);
            let local = utc.with_timezone(&tz).to_rfc3339();
            events.push((
                utc,
                json!({
                    "term": term,
                    "name": name,
                    "utc": utc.to_rfc3339_opts(chrono::SecondsFormat::Secs, true),
                    "local": local,
                    "jd_ut": jd,
                }),
            ));
        }
    }
    events.sort_by_key(|(utc, _)| *utc);
    let doc = json!({
        "version": "CAL-DATA-v0.1",
        "status": "PENDING",
        "reference_tz": "+08:00",
        "source": "mingli-astro 1.2.0 (Meeus truncated); generated by tools/gen-cal",
        "generated_at": "2026-11-03",
        "events": events.into_iter().map(|(_, v)| v).collect::<Vec<_>>(),
    });
    write_json(&root.join("jieqi.json"), &doc);
    println!("jieqi events: {}", doc["events"].as_array().unwrap().len());
}

fn jd_to_utc(jd: f64) -> DateTime<Utc> {
    let unix = (jd - 2440587.5) * 86400.0;
    let secs = unix.floor() as i64;
    let nanos = ((unix - unix.floor()) * 1_000_000_000.0).round() as u32;
    Utc.timestamp_opt(secs, nanos.min(999_999_999))
        .single()
        .expect("合法时间戳")
}

fn gen_baselines(cal_dir: &Path) {
    let data = cal::CalData::load(cal_dir).expect("加载历法数据");
    let baseline_dir = cal_dir.join("baseline");
    std::fs::create_dir_all(&baseline_dir).unwrap();
    let tz = FixedOffset::east_opt(8 * 3600).unwrap();

    for year in [2025, 2026] {
        let mut days = Vec::new();
        let mut date = chrono::NaiveDate::from_ymd_opt(year, 1, 1).unwrap();
        while date.year() == year {
            let naive = date.and_hms_opt(12, 0, 0).unwrap();
            let instant = tz.from_local_datetime(&naive).single().unwrap();
            let result = cal::query(
                &data,
                &cal::CalQuery {
                    time: cal::CalTime::Instant(instant),
                    timezone: "Asia/Shanghai".into(),
                    day_bound: cal::DayBound::Zichu,
                },
            )
            .expect("历法查询");
            days.push(json!({
                "date": date.format("%Y-%m-%d").to_string(),
                "lunar": result.lunar,
                "jieqi": result.jieqi.current,
                "month_branch": result.jieqi_month_branch.branch,
                "ganzhi": result.ganzhi,
                "xun": result.xun,
            }));
            date += chrono::Duration::days(1);
        }
        let doc = json!({
            "version": "CAL-BASELINE-v0.1",
            "status": "PENDING",
            "source": "generated by tools/gen-cal from CAL-DATA-v0.1; anchors cross-checked independently",
            "timezone": "Asia/Shanghai",
            "day_bound": "ZICHU",
            "year": year,
            "days": days,
        });
        write_json(&baseline_dir.join(format!("{year}.json")), &doc);
        println!("baseline {year}: {}", doc["days"].as_array().unwrap().len());
    }
}

fn write_json(path: &Path, value: &serde_json::Value) {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).unwrap();
    }
    std::fs::write(path, serde_json::to_string_pretty(value).unwrap()).unwrap();
    println!("wrote {}", path.display());
}
